#!/usr/bin/env node
// GENERATE THE TYPESCRIPT VIEW OF THE ZONE DOMAIN (R22).
//
//   node scripts/gen-zone-domain.mjs           # write web/src/types/zoneDomain.generated.ts
//   node scripts/gen-zone-domain.mjs --check   # fail if it is stale (used by the battery)
//
// WHY
// ---
// `zone_domain!` in crates/ds-core/src/zone.rs is the ONE place a zone type may
// be declared. Rust reads it directly. TypeScript could not: `isGroundZone` is
// called by the canvas painter mid-frame and by every export module, none of
// which can await a wasm round-trip — so `GROUND_ZONES` was a hand-authored
// array, which is a SECOND AUTHORING PATH and exactly what R22 forbids.
//
// Belief attempt five measured the cost: a ninth variant declared ground in Rust
// left `is_ground_zone(Utility)` true in Rust and `isGroundZone('Utility')`
// false in TypeScript, with every board green.
//
// So the TS view is GENERATED by EVALUATING the core (R20 — the value, not the
// form): load the compiled wasm, call `zone_type_names()` and
// `ground_zone_types()`, write what they answer. No parsing of Rust source, so a
// macro, an `if`, or a prose comment cannot mislead it.
//
// STALENESS IS A BUILD FAILURE, NOT A RUNTIME HOPE. `make wasm` regenerates this
// file, and `--check` is a battery step: if the checked-in file disagrees with
// what the core answers, the build is red. There is no path where the two drift
// and something merely notices later.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const WASM_DIR = path.join(REPO, 'web/src/wasm')
const OUT = path.join(REPO, 'web/src/types/zoneDomain.generated.ts')
const CHECK = process.argv.includes('--check')

if (!fs.existsSync(path.join(WASM_DIR, 'ds_core_bg.wasm'))) {
  console.error('gen-zone-domain FAIL: no wasm — run `make wasm` first.')
  process.exit(1)
}
const core = await import(pathToFileURL(path.join(WASM_DIR, 'ds_core.js')).href)
core.initSync({ module: fs.readFileSync(path.join(WASM_DIR, 'ds_core_bg.wasm')) })

for (const fn of ['zone_type_names', 'ground_zone_types']) {
  if (typeof core.Editor[fn] !== 'function') {
    console.error(`gen-zone-domain FAIL: the core exports no ${fn}() — rebuild the wasm.`)
    process.exit(1)
  }
}
const all = core.Editor.zone_type_names()
const ground = core.Editor.ground_zone_types()

// Non-vacuity: a generator that emits an empty domain would make every consumer
// trivially agree with it.
if (!Array.isArray(all) || all.length < 4 || !Array.isArray(ground) || ground.length === 0) {
  console.error(`gen-zone-domain FAIL: the core answered all=${JSON.stringify(all)} ground=${JSON.stringify(ground)} — refusing to write a degenerate domain.`)
  process.exit(1)
}
if (!ground.every((g) => all.includes(g))) {
  console.error(`gen-zone-domain FAIL: ground ${JSON.stringify(ground)} names a type outside ${JSON.stringify(all)}.`)
  process.exit(1)
}

const body = `// GENERATED by scripts/gen-zone-domain.mjs — DO NOT EDIT.
//
// The TypeScript view of the zone domain, produced by EVALUATING the compiled
// core: \`Editor.zone_type_names()\` and \`Editor.ground_zone_types()\`. The single
// authoring point is \`zone_domain!\` in crates/ds-core/src/zone.rs.
//
// Editing this file by hand recreates the second authoring path that let a
// ninth variant be ground in Rust and not-ground in TypeScript with every board
// green. \`make wasm\` regenerates it; \`node scripts/gen-zone-domain.mjs --check\`
// is a battery step, so staleness is a build failure.

import type { ZoneType } from './doc.ts'

/** Every \`ZoneType\`, in declaration order. */
export const ALL_ZONE_TYPES: readonly ZoneType[] = [
${all.map((t) => `  '${t}',`).join('\n')}
]

/** The types the published fold turns into circulation, plus circulation. */
export const GENERATED_GROUND_ZONES: readonly ZoneType[] = [
${ground.map((t) => `  '${t}',`).join('\n')}
]
`

if (CHECK) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (have !== body) {
    console.error(
      'gen-zone-domain FAIL: web/src/types/zoneDomain.generated.ts is STALE.\n' +
        `  core says all=${JSON.stringify(all)}\n` +
        `           ground=${JSON.stringify(ground)}\n` +
        '  Run `make wasm` (or `node scripts/gen-zone-domain.mjs`) and commit the result.\n' +
        '  A stale generated domain is the authored-domain defect wearing a generator.',
    )
    process.exit(1)
  }
  console.log(`gen-zone-domain OK — ${all.length} types, ${ground.length} ground, generated file matches the core`)
  process.exit(0)
}

fs.writeFileSync(OUT, body)
console.log(`gen-zone-domain wrote ${path.relative(REPO, OUT)} — ${all.length} types, ${ground.length} ground`)

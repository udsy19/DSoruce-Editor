// Freeze the sample plate's boundary so the RUST fixtures can build the same
// document the browser builds.
//
// WHY THIS EXISTS. Queue 3's standing rule is that every gate runs against two
// populations — freshly generated plans AND edited ones. The edited fixtures
// have to exist on both sides of the wasm boundary: Rust (cargo test, the
// invariant battery) and the web harness (captures, pixel gates). The plate
// itself comes from a DXF, and DXF parsing lives in TypeScript — so the ONE
// thing that crosses is this boundary polygon, captured here once and checked in
// as a stamped artifact, exactly like a golden.
//
// Run from repo root:  node scripts/capture-plate-fixture.mjs
// Output:              crates/ds-core/fixtures/plate-furniture-plan.json
//
// The output is FROZEN. Re-running it after an importer change is a
// re-capture event: the fixtures move, the invariant battery re-runs, and the
// ledger records what moved. Do not regenerate it to make a test pass.

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(here, '..')

const webRequire = createRequire(path.join(ROOT, 'web/package.json'))
const esbuildPath = createRequire(webRequire.resolve('vite')).resolve('esbuild')
const { build } = await import(pathToFileURL(esbuildPath).href)
let seq = 0
const bundle = async (entry) => {
  const out = path.join(os.tmpdir(), `plate-fx-${process.pid}-${seq++}.mjs`)
  await build({ entryPoints: [entry], outfile: out, bundle: true, format: 'esm', platform: 'node', logLevel: 'silent' })
  const mod = await import(pathToFileURL(out).href)
  fs.rmSync(out, { force: true })
  return mod
}

const { parseDrawing } = await bundle(path.join(ROOT, 'web/src/import/dxf.ts'))
const { extractPlate } = await bundle(path.join(ROOT, 'web/src/import/testfit.ts'))

const dxfPath = path.join(ROOT, 'samples/furniture-plan.dxf')
const drawing = parseDrawing(fs.readFileSync(dxfPath, 'utf8'))
const plate = extractPlate(drawing)

if (!plate?.boundary?.length) {
  console.error('extractPlate produced no boundary — refusing to write a fixture')
  process.exit(1)
}

const round = (v) => Math.round(v * 1e6) / 1e6
const boundary = plate.boundary.map(([x, y]) => [round(x), round(y)])

const out = {
  note: 'FROZEN. Generated by scripts/capture-plate-fixture.mjs from samples/furniture-plan.dxf.',
  source: 'samples/furniture-plan.dxf',
  method: plate.provenance?.method ?? 'unknown',
  areaM2: round(plate.areaM2),
  boundary,
}

const dest = path.join(ROOT, 'crates/ds-core/fixtures/plate-furniture-plan.json')
fs.mkdirSync(path.dirname(dest), { recursive: true })
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + '\n')

// The tooling-layer rule (gate-independence.md): a script that reports its own
// success proves nothing. Re-read what we wrote and assert it parses back to the
// same vertex count before claiming anything.
const back = JSON.parse(fs.readFileSync(dest, 'utf8'))
if (back.boundary.length !== boundary.length) {
  console.error('write did not take — refusing to report success')
  process.exit(1)
}
console.log(`wrote ${dest}: ${boundary.length} vertices, ${out.areaM2.toFixed(2)} m² (${out.method})`)
